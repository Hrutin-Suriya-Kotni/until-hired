#!/usr/bin/env python3
"""until-hired knowledge graph: what the candidate can prove, what the market asks for, and the gap between.

Python 3.9+, standard library only, no network access.

Files (in the knowledge folder, <workspace>/knowledge):
  graph.json              nodes (skill, project, role, gap, resource) and the edges between them
  market.json             how often each skill appears in the job descriptions scored so far
  events.jsonl            every skill-level change (who can claim what, and since when)
  lessons.pending.jsonl   lessons proposed by agents, waiting for the candidate's OK
  LEARNINGS.md            approved lessons (every session reads them, so only the candidate approves)
  GAPS.md / KNOWLEDGE.md  generated by `gaps --write` / `summary --write`

Skill levels (be strict, the candidate's interviews depend on it):
  evidenced  done in real work or a public project, with something to point at
  claimed    the candidate says so, but there is nothing to point at yet
  learning   in progress
  none       not known (recorded so the agent never claims it)

Text copied from a job post, email or web page goes in a JSON file (--json FILE), never on the
command line. Run `knowledge.py <command> -h` for each command's options.
"""
import datetime as dt
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from uhlib import (EXIT_DUP, EXIT_INPUT, LONG, SHORT, Cli, Lock, __version__, append_line,  # noqa: E402
                   atomic_write, fail, load_json_file, md, now, sanitize, text, today)

EXIT_NOT_CLAIMABLE = EXIT_DUP          # 3: at least one skill may not be claimed
LEVELS = ["evidenced", "claimed", "learning", "none"]
LESSON_KINDS = ["wait", "limit", "form", "selector", "timing", "search", "other"]
MAX_SKILLS_PER_JD = 100
ALIASES = {
    "k8s": "kubernetes", "js": "javascript", "ts": "typescript", "py": "python",
    "llms": "llm", "large language models": "llm", "genai": "generative ai", "gen ai": "generative ai",
    "ml": "machine learning", "dl": "deep learning", "cv": "computer vision", "nlp": "natural language processing",
    "rag": "retrieval augmented generation", "asr": "speech recognition", "stt": "speech recognition",
    "tts": "text to speech", "aws": "amazon web services", "gcp": "google cloud", "postgres": "postgresql",
    "react.js": "react", "reactjs": "react", "node": "node.js", "nodejs": "node.js", "golang": "go",
    "sklearn": "scikit-learn", "tf": "tensorflow", "ci/cd": "ci cd",
}


def default_dir() -> Path:
    env = os.environ.get("UNTIL_HIRED_KNOWLEDGE")
    if env:
        return Path(env)
    here = Path(__file__).resolve().parent
    if here.name == "bin":
        return here.parent / "knowledge"
    return Path.cwd() / "career" / "knowledge"


def norm(s: str) -> str:
    s = re.sub(r"\s+", " ", sanitize(s).lower())[:120].strip()
    return ALIASES.get(s, s)


def nid(kind, label):
    return f"{kind}:{re.sub(r'[^a-z0-9.+#]+', '-', norm(label)).strip('-')}"


def split_list(s):
    items = [norm(x) for x in re.split(r"[,;\n]", s or "") if x.strip()]
    if len(items) > MAX_SKILLS_PER_JD:
        fail(f"too many skills ({len(items)}); the limit is {MAX_SKILLS_PER_JD}", EXIT_INPUT)
    return [x for x in items if x]


def log(d: Path, **kw):
    append_line(d / "events.jsonl", json.dumps({"t": now(), **kw}, ensure_ascii=False))


class KB:
    def __init__(self, d: Path):
        self.d = d
        self.gp, self.mp = d / "graph.json", d / "market.json"
        if not self.gp.exists():
            fail(f"No knowledge graph at {d}. Run setup_workspace.py (the agent-setup skill) first.")
        self.g = load_json_file(self.gp, None)
        self.m = load_json_file(self.mp, {"jds": 0, "skills": {}})
        if not isinstance(self.g.get("nodes"), dict) or not isinstance(self.g.get("edges"), list):
            fail("graph.json is missing 'nodes' or 'edges'. Nothing was changed; restore graph.json.bak.")
        self.m.setdefault("jds", 0)
        self.m.setdefault("skills", {})

    def save(self):
        atomic_write(self.mp, json.dumps(self.m, indent=1, ensure_ascii=False))
        atomic_write(self.gp, json.dumps(self.g, indent=1, ensure_ascii=False))

    def node(self, kind, label, **attrs):
        i = nid(kind, label)
        n = self.g["nodes"].setdefault(i, {"type": kind, "label": sanitize(label)[:200], "attrs": {}, "added": str(today())})
        n["attrs"].update({k: v for k, v in attrs.items() if v not in (None, "")})
        n["updated"] = str(today())
        return i

    def edge(self, s, t, kind, **attrs):
        for e in self.g["edges"]:
            if e["s"] == s and e["t"] == t and e["type"] == kind:
                e.setdefault("attrs", {}).update(attrs)
                return
        self.g["edges"].append({"s": s, "t": t, "type": kind, "attrs": attrs, "added": str(today())})

    def skill_level(self, skill):
        n = self.g["nodes"].get(nid("skill", skill))
        return n["attrs"].get("level", "none") if n else "absent"

    def set_level(self, si, level, why):
        attrs = self.g["nodes"][si]["attrs"]
        old = attrs.get("level")
        if old != level:
            attrs["level"] = level
            log(self.d, type="level", skill=si, **{"from": old or "absent", "to": level, "why": why})


def locked(d):
    return Lock(d, what="knowledge graph")


def cmd_init(a):
    a.dir.mkdir(parents=True, exist_ok=True)
    with locked(a.dir):
        gp, mp = a.dir / "graph.json", a.dir / "market.json"
        if not gp.exists():
            atomic_write(gp, json.dumps({"version": 1, "nodes": {}, "edges": []}, indent=1))
        if not mp.exists():
            atomic_write(mp, json.dumps({"jds": 0, "skills": {}}, indent=1))
        (a.dir / "events.jsonl").touch()
    print(f"knowledge graph ready: {a.dir}")


def require(**kw):
    missing = [k for k, v in kw.items() if not v]
    if missing:
        fail(f"missing required field(s): {', '.join(missing)}", EXIT_INPUT)


def cmd_skill(a):
    name, evidence = text(a.name, "name", 120), text(a.evidence, "evidence", LONG)
    project, note = text(a.project, "project"), text(a.note, "note", LONG)
    require(name=name, level=a.level)
    if a.level == "evidenced" and not evidence:
        fail('evidenced needs "evidence": something the candidate can point at (a link, a repo, a role)', EXIT_INPUT)
    with locked(a.dir):
        kb = KB(a.dir)
        i = kb.node("skill", norm(name), evidence=evidence, note=note)
        kb.set_level(i, a.level, "skill")
        if project:
            kb.edge(kb.node("project", project), i, "uses")
        kb.save()
    print(json.dumps({"skill": i, "level": a.level}))


def cmd_project(a):
    name, skills = text(a.name, "name"), text(a.skills, "skills", LONG)
    evidence, summary, role = text(a.evidence, "evidence", LONG), text(a.summary, "summary", LONG), text(a.role, "role")
    require(name=name, skills=skills)
    with locked(a.dir):
        kb = KB(a.dir)
        p = kb.node("project", name, summary=summary, evidence=evidence, role=role)
        for s in split_list(skills):
            si = kb.node("skill", s)
            if "level" not in kb.g["nodes"][si]["attrs"]:
                kb.set_level(si, "evidenced" if evidence else "claimed", f"project {nid('project', name)}")
            kb.edge(p, si, "uses")
        kb.save()
    print(json.dumps({"project": p}))


def cmd_jd(a):
    """Record the skills one scored job description asks for: this builds the market picture."""
    company, role, track = text(a.company, "company"), text(a.role, "role"), text(a.track, "track", 60)
    must, nice = split_list(text(a.must, "must", LONG)), split_list(text(a.skills, "skills", LONG))
    job_id = text(a.job_id, "job_id", 10)
    require(company=company, role=role)
    with locked(a.dir):
        kb = KB(a.dir)
        r = kb.node("role", f"{company} - {role}", job_id=job_id, track=track)
        seen = set()
        for s in must + nice:
            if s in seen:
                continue
            seen.add(s)
            si = kb.node("skill", s)
            kb.edge(r, si, "requires", must=s in must)
            ms = kb.m["skills"].setdefault(s, {"count": 0, "must": 0, "tracks": {}})
            ms["count"] += 1
            ms["must"] += 1 if s in must else 0
            if track:
                ms["tracks"][track] = ms["tracks"].get(track, 0) + 1
        kb.m["jds"] = kb.m.get("jds", 0) + 1
        kb.m["updated"] = str(today())
        kb.save()
    print(json.dumps({"recorded_skills": len(seen)}))


def cmd_gap(a):
    """Record a gap that showed up in an interview, a rejection or feedback."""
    topic, source = text(a.topic, "topic", 120), text(a.source, "source")
    note, skill, severity = text(a.note, "note", LONG), text(a.skill, "skill", 120), text(a.severity, "severity", 20)
    require(topic=topic, source=source)
    with locked(a.dir):
        kb = KB(a.dir)
        g = kb.node("gap", topic, severity=severity)
        ev = kb.g["nodes"][g]["attrs"].setdefault("evidence", [])
        ev.append({"date": str(today()), "source": source, "note": note or ""})
        if skill:
            kb.edge(g, kb.node("skill", norm(skill)), "about")
        kb.save()
    print(json.dumps({"gap": g, "mentions": len(ev)}))


def cmd_learn(a):
    """Track learning toward a skill; a public proof moves it to evidenced."""
    skill, resource, proof = text(a.skill, "skill", 120), text(a.resource, "resource"), text(a.proof, "proof", LONG)
    require(skill=skill)
    status = a.status or "started"
    with locked(a.dir):
        kb = KB(a.dir)
        si = kb.node("skill", norm(skill))
        attrs = kb.g["nodes"][si]["attrs"]
        if resource:
            kb.edge(si, kb.node("resource", resource), "learning_from")
        if proof:
            attrs["evidence"] = proof
            kb.set_level(si, "evidenced", "learn --proof")
        elif attrs.get("level") in (None, "none", "claimed"):
            kb.set_level(si, "learning", "learn")
        attrs["learning_status"] = status
        kb.save()
    print(json.dumps({"skill": si, "level": attrs["level"], "status": status}))


def gap_rows(kb: KB, top: int):
    interview = {i: n for i, n in kb.g["nodes"].items() if n.get("type") == "gap"}
    about = {e["s"]: e["t"] for e in kb.g["edges"] if e.get("type") == "about"}
    jds = max(kb.m.get("jds", 0), 1)
    rows = []
    for s, ms in kb.m["skills"].items():
        level = kb.skill_level(s)
        hits = sum(len(n["attrs"].get("evidence", [])) for gi, n in interview.items() if about.get(gi) == nid("skill", s))
        score = ms["count"] + ms["must"] + 3 * hits
        cls = {"evidenced": "STRENGTH", "claimed": "UNPROVEN", "learning": "LEARNING"}.get(level, "MISSING")
        if hits and cls == "STRENGTH":
            cls = "DEEPEN"
        rows.append({"skill": s, "class": cls, "level": level, "in_jds": ms["count"], "must": ms["must"],
                     "share": round(100.0 * ms["count"] / jds), "interview_hits": hits, "score": score})
    for gi, n in interview.items():
        if gi not in about:
            hits = len(n["attrs"].get("evidence", []))
            rows.append({"skill": n["label"], "class": "INTERVIEW", "level": "-", "in_jds": 0, "must": 0,
                         "share": 0, "interview_hits": hits, "score": 3 * hits})
    rows.sort(key=lambda r: -r["score"])
    return rows[:top] if top else rows


ADVICE = {
    "MISSING": "In demand and not yours yet. Close it if it fits the target track: smallest proof project, then claim it.",
    "UNPROVEN": "You say you can, but there is nothing to show. Highest interview risk: build a small public proof.",
    "LEARNING": "Keep going; finish the proof so it can move to evidenced.",
    "DEEPEN": "A strength that interviewers still probed: prepare a deeper answer and one concrete story.",
    "STRENGTH": "Lead with it in resumes, notes and interviews.",
    "INTERVIEW": "Raised in interviews: prepare an honest answer and one proof.",
}


def cmd_gaps(a):
    kb = KB(a.dir)
    rows = gap_rows(kb, a.top)
    jds = kb.m.get("jds", 0)
    if a.format == "json":
        print(json.dumps({"jds": jds, "rows": rows}, ensure_ascii=False))
        return
    if not rows:
        print("No market data yet: score some job descriptions first (knowledge.py jd ...).")
        return
    print(f"based on {jds} job descriptions")
    print(f"{'skill':<34} {'class':<9} {'in JDs':>7} {'must':>5} {'intvw':>5}")
    for r in rows:
        print(f"{r['skill'][:34]:<34} {r['class']:<9} {str(r['share']) + '%':>7} {r['must']:>5} {r['interview_hits']:>5}")
    if a.write:
        lines = [f"# Skill and market gaps ({today()})", "",
                 f"Based on {jds} scored job descriptions and the interview debriefs. "
                 "Score = times asked + times required + 3 x interview mentions.", "",
                 "| Skill | Class | In JDs | Required | Interview mentions | What to do |", "|---|---|---|---|---|---|"]
        for r in rows:
            lines.append(f"| {md(r['skill'])} | {r['class']} | {r['share']}% | {r['must']} | {r['interview_hits']} | {ADVICE[r['class']]} |")
        lines += ["", "Classes: STRENGTH (evidenced and in demand), DEEPEN (strength still probed), UNPROVEN (claimed, no proof),",
                  "LEARNING (in progress), MISSING (in demand, not yours), INTERVIEW (raised in interviews, not a JD skill).", ""]
        with locked(a.dir):
            atomic_write(a.dir / "GAPS.md", "\n".join(lines))
        print(f"wrote {a.dir / 'GAPS.md'}")


def cmd_summary(a):
    kb = KB(a.dir)
    by_level = {lv: [] for lv in LEVELS}
    for n in kb.g["nodes"].values():
        if n.get("type") == "skill":
            by_level.setdefault(n["attrs"].get("level", "none"), []).append(n["label"])
    projects = [n for n in kb.g["nodes"].values() if n.get("type") == "project"]
    uses = {}
    for e in kb.g["edges"]:
        if e.get("type") == "uses" and e["t"] in kb.g["nodes"]:
            uses.setdefault(e["s"], []).append(kb.g["nodes"][e["t"]]["label"])
    top_market = sorted(kb.m["skills"].items(), key=lambda kv: -(kv[1]["count"] + kv[1]["must"]))[:15]
    lines = [f"# Knowledge graph summary ({today()})", "", "## Skills by level", ""]
    for lv in LEVELS:
        lines.append(f"- **{lv}** ({len(by_level.get(lv, []))}): " + ", ".join(md(x) for x in sorted(by_level.get(lv, []))))
    lines += ["", "## Projects", ""]
    for p in projects:
        pid = nid("project", p["label"])
        ev = p["attrs"].get("evidence", "")
        lines.append(f"- **{md(p['label'])}**: {', '.join(md(x) for x in sorted(uses.get(pid, [])))}" + (f" ({md(ev)})" if ev else ""))
    lines += ["", f"## What the market asks for ({kb.m.get('jds', 0)} job descriptions)", ""]
    for s, ms in top_market:
        lines.append(f"- {md(s)}: in {ms['count']} JDs, required in {ms['must']} (you: {kb.skill_level(s)})")
    out = "\n".join(lines) + "\n"
    if a.write:
        with locked(a.dir):
            atomic_write(a.dir / "KNOWLEDGE.md", out)
        print(f"wrote {a.dir / 'KNOWLEDGE.md'}")
    else:
        print(out)


def cmd_claimable(a):
    """Which of these skills may the candidate claim? Only evidenced ones (exit 3 otherwise)."""
    skills = text(a.skills, "skills", LONG)
    require(skills=skills)
    kb = KB(a.dir)
    res = {s: kb.skill_level(s) for s in split_list(skills)}
    print(json.dumps(res, indent=2, ensure_ascii=False))
    if any(v != "evidenced" for v in res.values()):
        sys.exit(EXIT_NOT_CLAIMABLE)


# ---------- lessons: proposed by agents, approved by the candidate ----------
def pending(d):
    p = d / "lessons.pending.jsonl"
    if not p.exists():
        return []
    rows = []
    for line in p.read_text(encoding="utf-8").splitlines():
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            pass
    return rows


def cmd_lesson(a):
    """Propose one lesson. It stays pending until the candidate approves it with `lessons --approve`."""
    lesson = text(a.text, "text", 300)
    platform = text(a.platform, "platform", 40)
    require(text=lesson)
    with locked(a.dir):
        rows = pending(a.dir)
        if any(r.get("text") == lesson for r in rows):
            print(json.dumps({"pending": len(rows), "duplicate": True}))
            return
        rows.append({"date": str(today()), "kind": a.kind, "platform": platform or "", "text": lesson})
        atomic_write(a.dir / "lessons.pending.jsonl", "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    print(json.dumps({"pending": len(rows)}))


def parse_numbers(s, n):
    try:
        nums = sorted({int(x) for x in (s or "").split(",") if x.strip()})
    except ValueError:
        fail("expected numbers like 1,3", EXIT_INPUT)
    if any(x < 1 or x > n for x in nums):
        fail(f"numbers must be between 1 and {n}", EXIT_INPUT)
    return nums


def cmd_lessons(a):
    rows = pending(a.dir)
    if not (a.approve or a.reject):
        if a.format == "json":
            print(json.dumps(rows, ensure_ascii=False))
        else:
            for i, r in enumerate(rows, 1):
                print(f"{i}. [{r.get('platform') or '-'}/{r.get('kind')}] {r.get('text')}")
            print(f"({len(rows)} pending; only the candidate approves: lessons --approve 1,2 / --reject 3)")
        return
    with locked(a.dir):
        rows = pending(a.dir)
        ok = parse_numbers(a.approve, len(rows))
        no = parse_numbers(a.reject, len(rows))
        if set(ok) & set(no):
            fail("a lesson cannot be approved and rejected at once", EXIT_INPUT)
        learn = a.dir / "LEARNINGS.md"
        cur = learn.read_text(encoding="utf-8") if learn.exists() else "# Learnings\n\n"
        add = [f"- {r['date']} [{md(r.get('platform') or '-')}/{r.get('kind')}] {md(r['text'])}" for i, r in enumerate(rows, 1) if i in ok]
        if add:
            atomic_write(learn, cur.rstrip("\n") + "\n" + "\n".join(add) + "\n")
        keep = [r for i, r in enumerate(rows, 1) if i not in ok and i not in no]
        atomic_write(a.dir / "lessons.pending.jsonl", "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in keep))
        log(a.dir, type="lessons", approved=len(ok), rejected=len(no))
    print(json.dumps({"approved": len(ok), "rejected": len(no), "pending": len(keep)}))


def build():
    c = Cli("knowledge.py", __doc__, default_dir(), "knowledge")
    c.cmd("init", cmd_init, "create the knowledge files (safe to re-run)")
    x = c.cmd("skill", cmd_skill, "set a skill's level"); x.add_argument("--name")
    x.add_argument("--level", choices=LEVELS); x.add_argument("--evidence"); x.add_argument("--project"); x.add_argument("--note")
    x = c.cmd("project", cmd_project, "add a project and the skills it shows"); x.add_argument("--name")
    x.add_argument("--skills", help="comma-separated (or a JSON list)"); x.add_argument("--evidence")
    x.add_argument("--summary"); x.add_argument("--role")
    x = c.cmd("jd", cmd_jd, "record the skills a scored job asks for"); x.add_argument("--company"); x.add_argument("--role")
    x.add_argument("--skills", help="nice-to-have (comma-separated or a JSON list)")
    x.add_argument("--must", help="must-have (comma-separated or a JSON list)"); x.add_argument("--job-id"); x.add_argument("--track")
    x = c.cmd("gap", cmd_gap, "record a gap from an interview, rejection or feedback"); x.add_argument("--topic")
    x.add_argument("--source"); x.add_argument("--note"); x.add_argument("--skill"); x.add_argument("--severity")
    x = c.cmd("learn", cmd_learn, "track learning; --proof moves the skill to evidenced"); x.add_argument("--skill")
    x.add_argument("--status", choices=["planned", "started", "done"]); x.add_argument("--resource"); x.add_argument("--proof")
    x = c.cmd("gaps", cmd_gaps, "rank gaps: market demand x your level x interview mentions")
    x.add_argument("--top", type=int, default=20); x.add_argument("--write", action="store_true")
    x.add_argument("--format", choices=["text", "json"], default="text")
    x = c.cmd("summary", cmd_summary, "what the graph knows"); x.add_argument("--write", action="store_true")
    x = c.cmd("claimable", cmd_claimable, "exit 3 unless every listed skill is evidenced"); x.add_argument("--skills")
    x = c.cmd("lesson", cmd_lesson, "propose one lesson (pending until the candidate approves)")
    x.add_argument("--text"); x.add_argument("--platform"); x.add_argument("--kind", choices=LESSON_KINDS, default="other")
    x = c.cmd("lessons", cmd_lessons, "list pending lessons; the candidate approves or rejects them")
    x.add_argument("--approve", help="numbers, e.g. 1,2"); x.add_argument("--reject", help="numbers, e.g. 3")
    x.add_argument("--format", choices=["text", "json"], default="text")
    return c


def main(argv=None):
    build().run(argv)


if __name__ == "__main__":
    main()
