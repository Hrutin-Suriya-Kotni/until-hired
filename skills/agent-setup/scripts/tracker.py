# ---------- storage ----------
def default_dir() -> Path:
    env = os.environ.get("UNTIL_HIRED_TRACKER")
    if env:
        return Path(env)
    here = Path(__file__).resolve().parent
    if here.name == "bin":                       # copied into <workspace>/bin by agent-setup
        return here.parent / "tracker"
    return Path.cwd() / "career" / "tracker"


def workspace(d: Path) -> Path:
    return d.resolve().parent


def jobs_of(d):
    return read_csv(d / "jobs.csv", JOB_FIELDS)


def log_event(d: Path, **kw):
    append_line(d / "events.jsonl", json.dumps({"t": now(), **kw}, ensure_ascii=False))


def read_events(d: Path):
    p = d / "events.jsonl"
    if not p.exists():
        return []
    out, bad = [], 0
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            bad += 1
    if bad:
        print(f"note: {bad} damaged line(s) in events.jsonl were skipped (kept in the file)", file=sys.stderr)
    return out


def parse_date(s):
    if not s:
        return None
    try:
        return dt.date.fromisoformat(s[:10])
    except ValueError:
        return None


def next_id(rows):
    return str(max([int(r["id"]) for r in rows if str(r.get("id", "")).isdigit()] or [0]) + 1)


def note_line(t):
    return f"[{today()}] {t}"


def folder_of(job) -> str:
    """The job's own materials folder, built by the tool (never from raw page text)."""
    return f"materials/{job['id']}-{slug(job['company'])}"


def need(d: Path):
    if not (d / "jobs.csv").exists():
        fail(f"No tracker at {d}. Run setup_workspace.py (the agent-setup skill) first.")


def out(obj):
    print(json.dumps(obj, ensure_ascii=False))


# ---------- normalisation ----------
def norm_company(s):
    s = (s or "").lower().replace("&", " and ")
    s = re.sub(r"[^\w\s]", " ", s)
    s = re.sub(LEGAL_SUFFIXES, " ", s)
    return re.sub(r"\s+", " ", s).strip()


def norm_role(s):
    s = (s or "").lower()
    s = re.sub(r"[^\w\s]", " ", s)
    s = re.sub(r"\b(sr)\b", "senior", s)
    s = re.sub(r"\b(jr)\b", "junior", s)
    return re.sub(r"\s+", " ", s).strip()


def norm_url(s):
    s = (s or "").strip()
    s = re.sub(r"[?#].*$", "", s)
    return s.rstrip("/").lower()


def check_status(v, allowed):
    if v and v not in allowed:
        fail(f"status must be one of {', '.join(allowed)}; got {v!r}", EXIT_INPUT)
    return v


def check_score(v):
    if v in (None, ""):
        return v
    try:
        x = float(v)
    except ValueError:
        fail(f"score: expected a number 0-100, got {v!r}", EXIT_INPUT)
    if not 0 <= x <= 100:
        fail(f"score: expected a number 0-100, got {v!r}", EXIT_INPUT)
    return f"{x:g}"


def check_id(v, what="id"):
    if not re.fullmatch(r"\d{1,7}", str(v or "")):
        fail(f"{what}: expected a number like 12, got {v!r}", EXIT_INPUT)
    return str(int(v))


