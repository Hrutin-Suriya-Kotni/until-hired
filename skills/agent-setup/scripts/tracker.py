def cmd_interview_add(a):
    d = a.dir; need(d)
    jid = check_id(a.job_id, "job_id")
    rnd, with_whom = text(a.round, "round"), text(getattr(a, "with"), "with")
    link, notes = text(a.link, "link", URL), text(a.notes, "notes", LONG)
    if not rnd:
        fail("interview-add: round is required", EXIT_INPUT)
    check_when("when", a.when)
    with Lock(d):
        jobs = jobs_of(d)
        j = next((x for x in jobs if x["id"] == jid), None)
        if not j:
            fail(f"no job #{jid}")
        p = d / "interviews.csv"
        ints = read_csv(p, INTERVIEW_FIELDS)
        row = {k: "" for k in INTERVIEW_FIELDS}
        row.update(id=next_id(ints), job_id=j["id"], company=j["company"], role=j["role"], when=a.when,
                   round=rnd, with_whom=with_whom or "", link=link or "", status="scheduled", notes=notes or "")
        ints.append(row)
        write_csv(p, INTERVIEW_FIELDS, ints)
        if j["status"] not in ("interview", "offer", "accepted"):
            old = j["status"]
            j["status"], j["updated"] = "interview", now()
            if not j["applied_on"]:
                j["applied_on"] = str(today())
            write_csv(d / "jobs.csv", JOB_FIELDS, jobs)
            log_event(d, type="job_updated", id=j["id"], evidence=True, **{"from": old, "to": "interview"})
        log_event(d, type="interview_added", id=row["id"], job_id=j["id"], when=a.when)
    out({"id": row["id"], "job_id": j["id"]})


def cmd_debrief(a):
    d = a.dir; need(d)
    iid = check_id(a.id)
    f = {k: text(getattr(a, k), k, LONG) for k in ("went_well", "probed", "struggled", "outcome")}
    rating = text(a.rating, "rating", 20)
    with Lock(d):
        p = d / "interviews.csv"
        ints = read_csv(p, INTERVIEW_FIELDS)
        i = next((x for x in ints if x["id"] == iid), None)
        if not i:
            fail(f"no interview #{iid}")
        i["status"] = "done"
        for k in ("went_well", "probed", "struggled", "outcome"):
            if f[k]:
                i[k] = f[k]
        if rating:
            i["self_rating"] = rating
        write_csv(p, INTERVIEW_FIELDS, ints)
        log_event(d, type="interview_debrief", id=i["id"], job_id=i["job_id"])
    out({"id": i["id"], "debrief": "saved"})


