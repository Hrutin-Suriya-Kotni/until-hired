def cmd_add(a):
    d = a.dir; need(d)
    f = {"company": text(a.company, "company"), "role": text(a.role, "role"), "url": text(a.url, "url", URL),
         "source": text(a.source, "source"), "location": text(a.location, "location"),
         "work_mode": text(a.work_mode, "work_mode"), "track": text(a.track, "track"),
         "notes": text(a.notes, "notes", LONG), "evidence": text(a.evidence, "evidence", LONG),
         "next": text(a.next, "next"), "contact": text(a.contact, "contact")}
    if not f["company"] or not f["role"]:
        fail("add: company and role are required", EXIT_INPUT)
    status = check_status(a.status or "found", STATUSES)
    score = check_score(a.score)
    check_date("next_on", a.next_on); check_date("applied_on", a.applied_on)
    p = d / "jobs.csv"
    with Lock(d):
        jobs = jobs_of(d)
        dups = find_duplicates(jobs, f["company"], f["role"], f["url"] or "")
        if dups and not a.force:
            out({"duplicate_of": brief(dups[0])})
            sys.exit(EXIT_DUP)
        hot = [j for j in company_rows(jobs, f["company"]) if j["status"] in HOT]
        row = {k: "" for k in JOB_FIELDS}
        row.update(id=next_id(jobs), added=now(), updated=now(), company=f["company"], role=f["role"],
                   location=f["location"] or "", work_mode=f["work_mode"] or "", source=f["source"] or "",
                   url=f["url"] or "", status=status, score=score or "", track=f["track"] or "",
                   notes=note_line(f["notes"]) if f["notes"] else "", evidence=f["evidence"] or "",
                   next_action=f["next"] or "", next_on=a.next_on or "", contact=f["contact"] or "")
        if status in IN_PROCESS:
            row["applied_on"] = a.applied_on or str(today())
        jobs.append(row)
        write_csv(p, JOB_FIELDS, jobs)
        log_event(d, type="job_added", id=row["id"], status=status, source=row["source"],
                  **({"evidence": True} if row["evidence"] else {}))
    if hot:
        print(f"WARNING: already in an active process at this company (#{hot[0]['id']}).", file=sys.stderr)
    out({"id": row["id"], "folder": folder_of(row), "status": status})


def cmd_update(a):
    d = a.dir; need(d)
    jid = check_id(a.id)
    f = {"note": text(a.note, "note", LONG), "evidence": text(a.evidence, "evidence", LONG),
         "next": text(a.next, "next"), "track": text(a.track, "track"), "url": text(a.url, "url", URL),
         "contact": text(a.contact, "contact"), "location": text(a.location, "location"),
         "work_mode": text(a.work_mode, "work_mode"), "source": text(a.source, "source")}
    check_status(a.status, STATUSES)
    score = check_score(a.score)
    check_date("next_on", a.next_on); check_date("applied_on", a.applied_on)
    p = d / "jobs.csv"
    with Lock(d):
        jobs = jobs_of(d)
        j = next((x for x in jobs if x["id"] == jid), None)
        if not j:
            fail(f"no job #{jid}")
        old = j["status"]
        if a.status:
            if a.status in IN_PROCESS and not j["applied_on"]:
                j["applied_on"] = a.applied_on or str(today())
            j["status"] = a.status
        if score is not None:
            j["score"] = score
        for field in ("track", "url", "contact", "location", "work_mode", "source"):
            if f[field] is not None:
                j[field] = f[field]
        if a.applied_on:
            j["applied_on"] = a.applied_on
        if f["next"] is not None:
            j["next_action"] = f["next"]
        if a.next_on is not None:
            j["next_on"] = a.next_on
        if f["note"]:
            j["notes"] = append_capped(j["notes"], note_line(f["note"]), "notes")
        if f["evidence"]:
            j["evidence"] = append_capped(j["evidence"], f["evidence"], "evidence")
        j["updated"] = now()
        write_csv(p, JOB_FIELDS, jobs)
        ev = {"from": old, "to": j["status"]} if a.status else {}
        if f["evidence"]:
            ev["evidence"] = True
        log_event(d, type="job_updated", id=j["id"], **ev)
    out({"id": j["id"], "company": j["company"], "role": j["role"], "from": old, "to": j["status"]})


