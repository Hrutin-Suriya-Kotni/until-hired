#!/usr/bin/env python3
"""until-hired tracker: the single source of truth for a job search.

Plain CSV files (open them in any spreadsheet app) plus an append-only event log.
Python 3.9+, standard library only, no network access.

Files (in the tracker folder, <workspace>/tracker):
  jobs.csv          every job found, prepared, applied to, and its outcome
  interviews.csv    every round, with the debrief
  contacts.csv      people you talk to (networking is optional)
  events.jsonl      one line per change: the audit trail the funnel is built from
  DASHBOARD.md      generated by `dashboard`

Text copied from a job post, email or web page goes in a JSON file, never on the command line:
  path=$(python3 bin/tracker.py new-input --agent scout)   # or just run it and read the path
  (write {"company": "...", "role": "...", "url": "..."} to that file with your file tool)
  python3 bin/tracker.py add --json <path> --score 82

Run `tracker.py <command> -h` for each command's options.
"""
