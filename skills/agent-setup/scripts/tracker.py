def cmd_list(a):
    d = a.dir; need(d)
    jobs = jobs_of(d)
    if a.status:
        want = set(a.status.split(","))
        jobs = [j for j in jobs if j["status"] in want]
    if a.company:
        jobs = company_rows(jobs, text(a.company, "company"))
    if a.min_score is not None:
        jobs = [j for j in jobs if j["score"] and float(j["score"]) >= a.min_score]
    jobs = jobs[-a.limit:] if a.limit else jobs
    if a.format == "json":
        print(json.dumps([brief(j) | {"score": j["score"], "source": j["source"]} for j in jobs], ensure_ascii=False))
        return
    for j in jobs:
        print(f"#{j['id']:>4} {j['status']:<11} {j['score'] or '-':>4}  {j['company'][:28]:<28} {j['role'][:44]:<44} {j['source']}")
    print(f"({len(jobs)} rows)")


def host_allowed(host, extra):
    host = host.lower().rstrip(".")
    for h in KNOWN_HIRING_HOSTS + [str(x).lower() for x in extra]:
        if host == h or host.endswith("." + h):
            return True
    return False


def cmd_disclose(a):
    """Check that a form's host may receive the candidate's answers, and log which fields (never values)."""
    d = a.dir; need(d)
    jid = check_id(a.id)
    host = (a.host or "").strip().lower()
    if "://" in host:
        host = host.split("://", 1)[1]
    host = host.split("/", 1)[0].split(":", 1)[0]
    if not re.fullmatch(r"[a-z0-9.-]{1,253}", host) or "." not in host:
        fail(f"host: expected a host name like boards.greenhouse.io, got {a.host!r}", EXIT_INPUT)
    fields = [x.strip() for x in (a.fields or "").split(",") if x.strip()]
    if not fields or not all(FIELD_NAME.fullmatch(x) for x in fields):
        fail("fields: expected answer names like name,email,phone,notice_period", EXIT_INPUT)
    cfg = load_config(d).get("apply", {}) or {}
    allowed = host_allowed(host, cfg.get("allowed_hosts", []) or [])
    with Lock(d):
        if not any(j["id"] == jid for j in jobs_of(d)):
            fail(f"no job #{jid}")
        log_event(d, type="disclosure", id=jid, host=host, fields=fields, allowed=allowed)
    if not allowed:
        out({"allowed": False, "host": host,
             "do": "Do not type anything into this form. Tell the candidate the host; only they can add it to "
                   "config.json apply.allowed_hosts."})
        sys.exit(EXIT_BLOCKED)
    out({"allowed": True, "host": host, "fields": fields})


def cmd_export(a):
    """Rows for a mirror (Google Sheets, Notion, Airtable): values already spreadsheet-safe."""
    d = a.dir; need(d)
    name = {"jobs": "jobs.csv", "interviews": "interviews.csv", "contacts": "contacts.csv"}[a.table]
