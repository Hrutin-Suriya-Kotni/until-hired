def due_items(d: Path, stale_days: int):
    jobs = jobs_of(d)
    ints = read_csv(d / "interviews.csv", INTERVIEW_FIELDS)
    contacts = read_csv(d / "contacts.csv", CONTACT_FIELDS)
    t = today()
    items = []
    for j in jobs:
        n = parse_date(j["next_on"])
        if n and n <= t and j["status"] not in CLOSED:
            items.append(("due", n, f"#{j['id']} {j['company']} | {j['role']}: {j['next_action'] or 'next step'}"))
        if j["status"] == "applied":
            last = parse_date(j["updated"]) or parse_date(j["applied_on"])
            if last and (t - last).days >= stale_days and not j["next_on"]:
                items.append(("stale", last, f"#{j['id']} {j['company']} | {j['role']}: no news for {(t - last).days} days. "
                              "Decide: one follow-up, or mark closed (no response)."))
        if j["status"] == "ready":
            items.append(("ready", parse_date(j["updated"]) or t, f"#{j['id']} {j['company']} | {j['role']}: prepared, waiting for submit"))
    for i in ints:
        w = parse_date(i["when"])
        if i["status"] == "scheduled" and w:
            if w < t:
                items.append(("debrief", w, f"interview #{i['id']} {i['company']} ({i['round']}) is past: run the debrief"))
            elif (w - t).days <= 2:
                items.append(("interview", w, f"interview #{i['id']} {i['company']} ({i['round']}) on {i['when']}: prep sheet ready?"))
    for c in contacts:
        n = parse_date(c["next_on"])
        if n and n <= t and c["status"] not in ("closed", "no-reply", "referral"):
            items.append(("contact", n, f"contact #{c['id']} {c['name']} ({c['company']}): follow up / next step"))
    order = {"interview": 0, "debrief": 1, "due": 2, "ready": 3, "contact": 4, "stale": 5}
    return sorted(items, key=lambda x: (order[x[0]], x[1]))


def cmd_due(a):
    d = a.dir; need(d)
    items = due_items(d, a.stale_days)
    if a.format == "json":
        print(json.dumps([{"kind": k, "text": t} for k, _, t in items], ensure_ascii=False))
        return
    for kind, _, t in items:
        print(f"[{kind}] {t}")
    if not items:
        print("nothing due")


def band(score):
    try:
        s = float(score)
    except (TypeError, ValueError):
        return "unscored"
    return "80+" if s >= 80 else "70-79" if s >= 70 else "60-69" if s >= 60 else "<60"


def funnel_data(d: Path):
    jobs = jobs_of(d)
    events = read_events(d)
    history = defaultdict(set)
    first_response = {}
    for e in events:
        if e.get("type") == "job_updated" and e.get("to"):
            history[e.get("id")].add(e["to"])
            if e["to"] in RESPONDED and e.get("id") not in first_response:
                first_response[e["id"]] = e.get("t", "")
    applied = [j for j in jobs if j["applied_on"] or j["status"] in IN_PROCESS | RESPONDED | {"withdrawn"}]

    def stage(j):
        reached = {"applied"}
        hist = history[j["id"]] | {j["status"]}
        if hist & RESPONDED:
            reached.add("response")
        if hist & {"assessment", "interview", "offer", "accepted"}:
            reached.add("positive")
        if hist & {"interview", "offer", "accepted"}:
            reached.add("interview")
        if hist & {"offer", "accepted"}:
            reached.add("offer")
        return reached

    def table(key):
        rows = defaultdict(Counter)
        for j in applied:
            for st in stage(j):
                rows[key(j) or "unknown"][st] += 1
        return {k: dict(v) for k, v in sorted(rows.items(), key=lambda kv: -kv[1]["applied"])}

    days = []
    for j in applied:
        if j["id"] in first_response and j["applied_on"]:
            a0, b0 = parse_date(j["applied_on"]), parse_date(first_response[j["id"]])
            if a0 and b0:
                days.append((b0 - a0).days)
    days.sort()
    return {
        "total_jobs": len(jobs),
        "by_status": dict(Counter(j["status"] for j in jobs)),
        "applied": len(applied),
        "by_source": table(lambda j: j["source"]),
        "by_track": table(lambda j: j["track"]),
        "by_score_band": table(lambda j: band(j["score"])),
        "median_days_to_response": days[len(days) // 2] if days else None,
    }


def rate(n, dnm):
    return f"{(100.0 * n / dnm):.0f}%" if dnm else "-"


def cmd_funnel(a):
    d = a.dir; need(d)
    f = funnel_data(d)
    if a.format == "json":
        print(json.dumps(f, indent=2, ensure_ascii=False))
        return
    print(f"jobs tracked: {f['total_jobs']}   applied: {f['applied']}   median days to first response: {f['median_days_to_response']}")
    print("status:", ", ".join(f"{k} {v}" for k, v in sorted(f["by_status"].items(), key=lambda kv: -kv[1])))
    for title in ("by_source", "by_track", "by_score_band"):
        print(f"\n{title.replace('_', ' ')}:  applied | response | positive | interview | offer")
        for k, c in f[title].items():
            ap = c.get("applied", 0)
            print(f"  {k[:22]:<22} {ap:>5} | {rate(c.get('response', 0), ap):>8} | {rate(c.get('positive', 0), ap):>8} |"
                  f" {rate(c.get('interview', 0), ap):>9} | {rate(c.get('offer', 0), ap):>5}")


def cmd_dashboard(a):
    d = a.dir; need(d)
    with Lock(d):
        jobs = jobs_of(d)
        ints = read_csv(d / "interviews.csv", INTERVIEW_FIELDS)
        f = funnel_data(d)
        mdr = f["median_days_to_response"]
        lines = [f"# Job search dashboard ({now()})", "",
                 f"**Tracked:** {f['total_jobs']} · **Applied:** {f['applied']} · "
                 f"**Median days to first response:** {mdr if mdr is not None else '-'}", "",
                 "## Needs attention", ""]
        lines += [f"- **{k}**: {md(t)}" for k, _, t in due_items(d, a.stale_days)] or ["- Nothing due."]
        lines += ["", "## Active processes", "", "| # | Company | Role | Status | Next | When |", "|---|---|---|---|---|---|"]
        act = [j for j in jobs if j["status"] in IN_PROCESS - {"applied"}]
        lines += [f"| {j['id']} | {md(j['company'])} | {md(j['role'])} | {j['status']} | {md(j['next_action'])} | {md(j['next_on'])} |"
                  for j in act] or ["| | none yet | | | | |"]
        up = sorted([i for i in ints if i["status"] == "scheduled"], key=lambda x: x["when"])
        lines += ["", "## Upcoming interviews", ""]
        lines += [f"- {md(i['when'])}: {md(i['company'])}, {md(i['round'])} ({md(i['with_whom'])})" for i in up] or ["- None scheduled."]
        lines += ["", "## Funnel by source", "", "| Source | Applied | Response | Interview | Offer |", "|---|---|---|---|---|"]
        for k, c in f["by_source"].items():
            ap = c.get("applied", 0)
            lines.append(f"| {md(k)} | {ap} | {rate(c.get('response', 0), ap)} | {rate(c.get('interview', 0), ap)} | {rate(c.get('offer', 0), ap)} |")
        lines += ["", "## Pipeline", ""]
        lines += [f"- {md(s)}: {n}" for s, n in sorted(f["by_status"].items(),
                                                       key=lambda kv: STATUSES.index(kv[0]) if kv[0] in STATUSES else 99)]
        atomic_write(d / "DASHBOARD.md", "\n".join(lines) + "\n")
    print(f"wrote {d / 'DASHBOARD.md'}")


