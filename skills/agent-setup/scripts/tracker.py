def cmd_contact_add(a):
    d = a.dir; need(d)
    f = {k: text(getattr(a, k), k) for k in ("name", "company", "title", "channel")}
    f["url"], f["hook"], f["notes"] = text(a.url, "url", URL), text(a.hook, "hook", LONG), text(a.notes, "notes", LONG)
    if not f["name"] or not f["company"]:
        fail("contact-add: name and company are required", EXIT_INPUT)
    with Lock(d):
        p = d / "contacts.csv"
        rows = read_csv(p, CONTACT_FIELDS)
        key = (f["name"].lower(), norm_company(f["company"]))
        for r in rows:
            if (r["name"].strip().lower(), norm_company(r["company"])) == key:
                out({"duplicate_of": {"id": r["id"], "name": r["name"], "status": r["status"]}})
                sys.exit(EXIT_DUP)
        row = {k: "" for k in CONTACT_FIELDS}
        row.update(id=next_id(rows), added=now(), name=f["name"], company=f["company"], title=f["title"] or "",
                   channel=f["channel"] or "", profile_url=f["url"] or "", hook=f["hook"] or "",
                   status="to-contact", notes=f["notes"] or "")
        rows.append(row)
        write_csv(p, CONTACT_FIELDS, rows)
        log_event(d, type="contact_added", id=row["id"])
    out({"id": row["id"]})


def cmd_contact_update(a):
    d = a.dir; need(d)
    cid = check_id(a.id)
    note = text(a.note, "note", LONG)
    check_status(a.status, CONTACT_STATUSES)
    check_date("next_on", a.next_on)
    with Lock(d):
        p = d / "contacts.csv"
        rows = read_csv(p, CONTACT_FIELDS)
        r = next((x for x in rows if x["id"] == cid), None)
