def build():
    c = Cli("tracker.py", __doc__, default_dir(), "tracker")
    c.cmd("init", cmd_init, "create the tracker files (safe to re-run)")
    x = c.cmd("new-input", cmd_new_input, "create a unique empty input file in <workspace>/.inbox and print its path")
    x.add_argument("--agent", default="agent", help="who will fill it, e.g. scout, applicant")

    x = c.cmd("check", cmd_check, "duplicate / active-process check before preparing or applying (exit 3 or 4)")
    x.add_argument("--company"); x.add_argument("--role"); x.add_argument("--url")
    x.add_argument("--days", type=int, default=30)

    x = c.cmd("add", cmd_add, "add a job; prints {id, folder, status}")
    for o in ("--company", "--role", "--url", "--source", "--location", "--work-mode", "--status", "--score",
              "--track", "--notes", "--evidence", "--next", "--next-on", "--contact", "--applied-on"):
        x.add_argument(o)
    x.add_argument("--force", action="store_true", help="add even if it looks like a duplicate")

    x = c.cmd("update", cmd_update, "change status, add a note, evidence or next step")
    x.add_argument("--id", required=True)
    for o in ("--status", "--note", "--evidence", "--next", "--next-on", "--score", "--track", "--url", "--contact",
              "--location", "--work-mode", "--source", "--applied-on"):
        x.add_argument(o)

    x = c.cmd("show", cmd_show, "one job with its interviews, as JSON"); x.add_argument("--id", required=True)
    x = c.cmd("folder", cmd_folder, "the job's materials folder (built by the tool)"); x.add_argument("--id", required=True)
    x.add_argument("--create", action="store_true")
    x = c.cmd("list", cmd_list, "list jobs"); x.add_argument("--status", help="comma-separated")
    x.add_argument("--company"); x.add_argument("--min-score", type=float); x.add_argument("--limit", type=int)
    x.add_argument("--format", choices=["text", "json"], default="text")

    x = c.cmd("disclose", cmd_disclose, "before typing answers into a form: check its host, log the field names (exit 6 = not allowed)")
    x.add_argument("--id", required=True); x.add_argument("--host", required=True, help="e.g. boards.greenhouse.io")
    x.add_argument("--fields", required=True, help="answer names, e.g. name,email,phone,notice_period")
    x = c.cmd("export", cmd_export, "spreadsheet-safe rows for a mirror, as a JSON array (header first)")
    x.add_argument("--table", choices=["jobs", "interviews", "contacts"], default="jobs")

    x = c.cmd("interview-add", cmd_interview_add, "schedule an interview round (moves the job to interview)")
    x.add_argument("--job-id", required=True); x.add_argument("--when", required=True, help="YYYY-MM-DD HH:MM")
    x.add_argument("--round", required=True); x.add_argument("--with", dest="with"); x.add_argument("--link"); x.add_argument("--notes")
    x = c.cmd("debrief", cmd_debrief, "save how an interview went"); x.add_argument("--id", required=True)
    for o in ("--went-well", "--probed", "--struggled", "--outcome"):
        x.add_argument(o)
    x.add_argument("--rating", help="self rating, e.g. 7/10")
    x = c.cmd("interviews", cmd_interviews, "list interviews"); x.add_argument("--upcoming", action="store_true")

    x = c.cmd("contact-add", cmd_contact_add, "add a networking contact")
    for o in ("--name", "--company", "--title", "--channel", "--url", "--hook", "--notes"):
        x.add_argument(o)
    x = c.cmd("contact-update", cmd_contact_update, "change a contact's status or add a note")
    x.add_argument("--id", required=True); x.add_argument("--status"); x.add_argument("--note"); x.add_argument("--next-on")

